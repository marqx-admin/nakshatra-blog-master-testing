from __future__ import annotations

from dataclasses import dataclass
import hashlib
import time
from typing import Any
from urllib.parse import urlsplit

from bp_domain.media import cdn_variant_url, publicly_deliverable


PUBLIC_CACHE_CONTROL = "public, max-age=31536000, immutable"
PRIVATE_CACHE_CONTROL = "private, no-store"
DENIED_CACHE_CONTROL = "no-store"


@dataclass(slots=True)
class CdnMediaDeliveryAdapter:
    """DOC-17 media delivery policy over an injected CDN purge client.

    This adapter never receives or returns object-store keys for anonymous delivery.
    The caller must resolve authoritative media/site/reference state first and pass
    the predicate inputs explicitly.  `purge_client`, when configured, is expected
    to expose an async or sync `purge_prefix(prefix)` operation.
    """

    media_cdn_origin: str
    purge_client: Any | None = None

    def public_url(
        self,
        *,
        site_key: str,
        site_id: str,
        site_status: str,
        media_id: str,
        media_site_id: str,
        media_status: str,
        variant_key: str,
        updated_at_epoch_ms: int,
        selected_by_public_projection: bool,
        namespace_matches_owner: bool,
        native_webp_verified: bool,
    ) -> tuple[str, str] | None:
        if not publicly_deliverable(
            media_status=media_status,
            media_site_id=media_site_id,
            site_id=site_id,
            site_status=site_status,
            selected_by_public_projection=selected_by_public_projection,
            namespace_matches_owner=namespace_matches_owner,
            native_webp_verified=native_webp_verified,
        ):
            return None
        return (
            cdn_variant_url(
                media_cdn_origin=self.media_cdn_origin,
                site_key=site_key,
                media_id=media_id,
                variant_key=variant_key,
                updated_at_epoch_ms=updated_at_epoch_ms,
            ),
            PUBLIC_CACHE_CONTROL,
        )

    @staticmethod
    def protected_cache_control() -> str:
        return PRIVATE_CACHE_CONTROL

    @staticmethod
    def denied_cache_control() -> str:
        return DENIED_CACHE_CONTROL

    async def purge_media_namespace(self, *, site_key: str, media_id: str) -> None:
        if not site_key or not media_id:
            raise ValueError("same-site media purge requires site_key and media_id")
        if self.purge_client is None:
            # No purge provider means no false success in production composition.
            raise RuntimeError("media CDN purge adapter is not configured")
        prefix = f"/m/{site_key}/{media_id}/"
        result = self.purge_client.purge_prefix(prefix)
        if hasattr(result, "__await__"):
            await result


@dataclass(slots=True)
class CloudFrontPurgeClient:
    """AWS CloudFront purge plumbing for the DOC-17 delivery adapter.

    The configured public CDN origin may be either the CloudFront distribution
    hostname or a distribution alias.  Distribution discovery is cached after the
    first purge.  This class accepts only the media namespace generated by
    ``CdnMediaDeliveryAdapter``; arbitrary invalidation paths are not a job input.
    """

    cloudfront_client: Any
    media_cdn_origin: str
    _distribution_id: str | None = None

    def _origin_host(self) -> str:
        parsed = urlsplit(self.media_cdn_origin)
        if parsed.scheme.lower() != "https" or not parsed.hostname:
            raise RuntimeError("staging/production media CDN origin must be an HTTPS host")
        return parsed.hostname.lower().rstrip(".")

    def _resolve_distribution_id(self) -> str:
        if self._distribution_id is not None:
            return self._distribution_id
        host = self._origin_host()
        marker: str | None = None
        matches: list[str] = []
        while True:
            kwargs = {} if marker is None else {"Marker": marker}
            response = self.cloudfront_client.list_distributions(**kwargs)
            listing = response.get("DistributionList") or {}
            for item in listing.get("Items") or []:
                distribution_host = str(item.get("DomainName") or "").lower().rstrip(".")
                aliases = item.get("Aliases") or {}
                alias_hosts = {str(value).lower().rstrip(".") for value in aliases.get("Items") or []}
                if host == distribution_host or host in alias_hosts:
                    distribution_id = str(item.get("Id") or "")
                    if distribution_id:
                        matches.append(distribution_id)
            if not listing.get("IsTruncated"):
                break
            marker = str(listing.get("NextMarker") or "")
            if not marker:
                raise RuntimeError("CloudFront distribution pagination is incomplete")
        matches = sorted(set(matches))
        if len(matches) != 1:
            raise RuntimeError("media CDN origin must resolve to exactly one CloudFront distribution")
        self._distribution_id = matches[0]
        return self._distribution_id

    def purge_prefix(self, prefix: str):
        if not prefix.startswith("/m/") or not prefix.endswith("/") or ".." in prefix.split("/"):
            raise ValueError("invalid media CDN purge namespace")
        path = prefix + "*"
        nonce = f"{time.time_ns()}:{path}"
        caller_reference = "bp-media-" + hashlib.sha256(nonce.encode("utf-8")).hexdigest()[:32]
        return self.cloudfront_client.create_invalidation(
            DistributionId=self._resolve_distribution_id(),
            InvalidationBatch={
                "Paths": {"Quantity": 1, "Items": [path]},
                "CallerReference": caller_reference,
            },
        )
