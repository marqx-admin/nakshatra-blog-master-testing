class AdminSearchPort(Protocol):
    """Authorized same-site candidate source for DOC-16 Admin/editorial search.

    The principal is passed deliberately: search ranking runs only *inside* the
    candidate set allowed by upstream content/permission rules.  The adapter must
    never use the search permission itself as authority to disclose Post content.
    """

    async def search_posts(self, context: SiteContext, *, principal: Any, q: str, status: str | None, page: int, page_size: int) -> tuple[list[dict[str, Any]], bool]: ...
    async def internal_links(self, context: SiteContext, *, principal: Any, q: str, page: int, page_size: int) -> tuple[list[dict[str, Any]], bool]: ...
    async def related_posts(self, context: SiteContext, *, principal: Any, post_id: str | None, q: str | None, page: int, page_size: int) -> tuple[list[dict[str, Any]], bool]: ...


